/**
 * Estadística exacta sin dependencias: beta incompleta regularizada (fracción continua de Lentz),
 * cuantil por bisección, cota inferior Clopper–Pearson y probabilidad posterior Beta.
 * Verificada en `test/stats.spec.ts` contra casos cerrados (`0,05^(1/n)`) y por simulación.
 */

function logGamma(x: number): number {
  // Lanczos (g = 7, n = 9).
  const c = [
    0.99999999999980993, 676.5203681218851, -1259.1392167224028, 771.32342877765313,
    -176.61502916214059, 12.507343278686905, -0.13857109526572012, 9.9843695780195716e-6,
    1.5056327351493116e-7,
  ];
  if (x < 0.5) return Math.log(Math.PI / Math.sin(Math.PI * x)) - logGamma(1 - x);
  const z = x - 1;
  let sum = c[0]!;
  for (let i = 1; i < 9; i += 1) sum += c[i]! / (z + i);
  const t = z + 7.5;
  return 0.5 * Math.log(2 * Math.PI) + (z + 0.5) * Math.log(t) - t + Math.log(sum);
}

function continuedFraction(a: number, b: number, x: number): number {
  const tiny = 1e-300;
  let c = 1;
  let d = 1 - ((a + b) * x) / (a + 1);
  if (Math.abs(d) < tiny) d = tiny;
  d = 1 / d;
  let h = d;
  for (let m = 1; m <= 500; m += 1) {
    const m2 = 2 * m;
    let aa = (m * (b - m) * x) / ((a + m2 - 1) * (a + m2));
    d = 1 + aa * d;
    if (Math.abs(d) < tiny) d = tiny;
    c = 1 + aa / c;
    if (Math.abs(c) < tiny) c = tiny;
    d = 1 / d;
    h *= d * c;
    aa = (-(a + m) * (a + b + m) * x) / ((a + m2) * (a + m2 + 1));
    d = 1 + aa * d;
    if (Math.abs(d) < tiny) d = tiny;
    c = 1 + aa / c;
    if (Math.abs(c) < tiny) c = tiny;
    d = 1 / d;
    const delta = d * c;
    h *= delta;
    if (Math.abs(delta - 1) < 1e-14) break;
  }
  return h;
}

/** I_x(a, b): CDF de Beta(a, b) en x. */
export function betaCdf(x: number, a: number, b: number): number {
  if (x <= 0) return 0;
  if (x >= 1) return 1;
  const front = Math.exp(
    logGamma(a + b) - logGamma(a) - logGamma(b) + a * Math.log(x) + b * Math.log(1 - x),
  );
  return x < (a + 1) / (a + b + 2)
    ? (front * continuedFraction(a, b, x)) / a
    : 1 - (front * continuedFraction(b, a, 1 - x)) / b;
}

/** Cuantil de Beta(a, b) por bisección (60 iteraciones: error < 1e-15). */
export function betaQuantile(p: number, a: number, b: number): number {
  let low = 0;
  let high = 1;
  for (let i = 0; i < 60; i += 1) {
    const mid = (low + high) / 2;
    if (betaCdf(mid, a, b) < p) low = mid;
    else high = mid;
  }
  return (low + high) / 2;
}

/**
 * Cota inferior unilateral Clopper–Pearson de una proporción con `successes` aciertos en `n`.
 * Con `successes = n` vale `alpha^(1/n)`.
 */
export function clopperPearsonLower(successes: number, n: number, alpha = 0.05): number {
  if (n === 0 || successes === 0) return 0;
  return betaQuantile(alpha, successes, n - successes + 1);
}
